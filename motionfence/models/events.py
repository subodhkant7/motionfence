"""Structured runtime event models for deterministic auditability and observability."""

from enum import Enum
from typing import Any, Dict
import time
import uuid
from pydantic import BaseModel, Field


class EventType(str, Enum):
    """Enumeration of standard lifecycle events in the MotionFence control loop."""
    INTENT_RECEIVED = "INTENT_RECEIVED"
    OBSERVATION_RECORDED = "OBSERVATION_RECORDED"
    ACTION_PROPOSED = "ACTION_PROPOSED"
    POLICY_EVALUATED = "POLICY_EVALUATED"
    ACTION_DENIED = "ACTION_DENIED"
    MORE_EVIDENCE_REQUIRED = "MORE_EVIDENCE_REQUIRED"
    ACTION_AUTHORIZED = "ACTION_AUTHORIZED"
    ACTION_EXECUTED = "ACTION_EXECUTED"
    POSTCONDITION_VERIFIED = "POSTCONDITION_VERIFIED"
    POSTCONDITION_FAILED = "POSTCONDITION_FAILED"
    # Phase 1: Model Provider Observability Events
    MODEL_REQUESTED = "MODEL_REQUESTED"
    MODEL_RESPONSE_RECEIVED = "MODEL_RESPONSE_RECEIVED"
    MODEL_RESPONSE_REJECTED = "MODEL_RESPONSE_REJECTED"
    MODEL_PROVIDER_ERROR = "MODEL_PROVIDER_ERROR"
    ACTION_PROPOSAL_VALIDATED = "ACTION_PROPOSAL_VALIDATED"
    # Phase 2A: Knowledge & Constraint Observability Events
    KNOWLEDGE_QUERY_REQUESTED = "KNOWLEDGE_QUERY_REQUESTED"
    KNOWLEDGE_RESULT_RECEIVED = "KNOWLEDGE_RESULT_RECEIVED"
    KNOWLEDGE_RESULT_REJECTED = "KNOWLEDGE_RESULT_REJECTED"
    CONSTRAINT_CANDIDATE_CREATED = "CONSTRAINT_CANDIDATE_CREATED"
    CONSTRAINT_VALIDATED = "CONSTRAINT_VALIDATED"
    CONSTRAINT_REJECTED = "CONSTRAINT_REJECTED"
    CONSTRAINT_ACTIVATED = "CONSTRAINT_ACTIVATED"
    CONSTRAINT_STALE = "CONSTRAINT_STALE"
    CONSTRAINT_CONFLICT = "CONSTRAINT_CONFLICT"
    # Phase 2B: Evidence Trust, Admissibility & Nemotron Observability Events
    SOURCE_ASSESSED = "SOURCE_ASSESSED"
    EVIDENCE_CLASSIFIED = "EVIDENCE_CLASSIFIED"
    EVIDENCE_CORROBORATED = "EVIDENCE_CORROBORATED"
    EVIDENCE_INSUFFICIENT = "EVIDENCE_INSUFFICIENT"
    CONSTRAINT_EXTRACTED = "CONSTRAINT_EXTRACTED"
    CONSTRAINT_ADMISSIBILITY_CHECKED = "CONSTRAINT_ADMISSIBILITY_CHECKED"
    CONSTRAINT_ADMISSIBLE = "CONSTRAINT_ADMISSIBLE"
    CONSTRAINT_NOT_ADMISSIBLE = "CONSTRAINT_NOT_ADMISSIBLE"
    # Phase 2C: Claim Grounding & Decision Integrity Observability Events
    CLAIM_EXTRACTED = "CLAIM_EXTRACTED"
    CLAIM_GROUNDING_STARTED = "CLAIM_GROUNDING_STARTED"
    CLAIM_GROUNDED = "CLAIM_GROUNDED"
    CLAIM_UNSUPPORTED = "CLAIM_UNSUPPORTED"
    CLAIM_INFERRED = "CLAIM_INFERRED"
    CLAIM_DISTORTED = "CLAIM_DISTORTED"
    CLAIM_SCOPE_MISMATCH = "CLAIM_SCOPE_MISMATCH"
    CLAIM_NEGATION_MISMATCH = "CLAIM_NEGATION_MISMATCH"
    CLAIM_CONDITION_LOST = "CLAIM_CONDITION_LOST"
    # Phase 2D: Decision Records, Deterministic Replay & Safety Enclave Observability Events
    DECISION_CREATED = "DECISION_CREATED"
    DECISION_FINALIZED = "DECISION_FINALIZED"
    DECISION_HASHED = "DECISION_HASHED"
    DECISION_REPLAYED = "DECISION_REPLAYED"
    REPLAY_MATCH = "REPLAY_MATCH"
    REPLAY_DIVERGENCE = "REPLAY_DIVERGENCE"
    INTEGRITY_FAILURE = "INTEGRITY_FAILURE"
    ENCLAVE_AUTHORIZATION_REQUESTED = "ENCLAVE_AUTHORIZATION_REQUESTED"
    ENCLAVE_AUTHORIZATION_GRANTED = "ENCLAVE_AUTHORIZATION_GRANTED"
    ENCLAVE_AUTHORIZATION_DENIED = "ENCLAVE_AUTHORIZATION_DENIED"


class RuntimeEvent(BaseModel):
    """Immutable structured log event capturing every step of the authorization loop."""
    event_id: str = Field(default_factory=lambda: f"evt_{uuid.uuid4().hex[:10]}")
    event_type: EventType = Field(..., description="Classification of the runtime event.")
    timestamp: float = Field(default_factory=time.time)
    message: str = Field(..., description="Human-readable event summary.")
    payload: Dict[str, Any] = Field(default_factory=dict, description="Machine-readable structured context.")
